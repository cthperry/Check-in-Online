"""Vercel 使用專案的 PostgreSQL 連線，本機仍支援 SQLite。"""
from contextlib import contextmanager

import psycopg
from psycopg.rows import dict_row


class Connection:
    def __init__(self, raw):
        self.raw = raw

    def execute(self, sql, args=()):
        return self.raw.execute(sql.replace("?", "%s"), args)

    def commit(self):
        self.raw.commit()

    def rollback(self):
        self.raw.rollback()


@contextmanager
def connect(url):
    with psycopg.connect(url, autocommit=True, row_factory=dict_row, connect_timeout=8) as raw:
        yield Connection(raw)


def begin(con):
    con.execute("BEGIN")
    # 對齊 SQLite 的寫入順序，跨執行個體也會依序檢查打卡版本。
    con.execute("SELECT pg_advisory_xact_lock(78368102)")


def initialize(url, schema):
    with connect(url) as con:
        with con.raw.transaction():
            con.execute("SELECT pg_advisory_xact_lock(78368102)")
            for stmt in schema.replace("id INTEGER PRIMARY KEY,", "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,").split(";"):
                if stmt.strip():
                    con.execute(stmt)
